// เช็คว่าตัวแปรเป็นชนิดข้อมูล (type) อะไร
// นำเข้าฟังก์ชัน type_name จากไลบรารีมาตรฐาน ใช้ดึงชื่อของชนิดข้อมูลออกมาเป็นข้อความ
use std::any::type_name;

// ฟังก์ชันแบบ generic: รับตัวแปรชนิดใดก็ได้ (T) แบบยืมค่า (&T)
// แล้วคืนชื่อชนิดข้อมูลของ T กลับมาเป็น &'static str
// ใช้ `_` เพราะไม่ได้ใช้ค่าของตัวแปรจริง ๆ ต้องการแค่ชนิดข้อมูลของมัน
fn type_of<T>(_: &T) -> &'static str {
    type_name::<T>()
}

fn main() {
    // การประกาศตัวแปรในภาษา Rust ใช้คำสั่ง `let` ตามด้วยชื่อตัวแปรและค่าที่ต้องการกำหนด
    // ตัวแปรใน Rust เปลี่ยนค่าไม่ได้ (immutable) โดยค่าเริ่มต้น ถ้าอยากเปลี่ยนค่าต้องใช้ `let mut`

    // Rust เดาชนิดข้อมูลให้เอง (type inference): "Faris" เป็นชนิด &str (ข้อความแบบยืม)
    let name = "Faris";
    // {} คือตำแหน่งที่จะแทนค่าตัวแปรลงในข้อความ
    println!("Hello, {}!", name);

    // ตัวเลขจำนวนเต็มที่ไม่ได้ระบุชนิด Rust จะใช้ i32 เป็นค่าเริ่มต้น
    let age = 20;
    println!("I am {} years old.", age);

    // ระบุชนิดข้อมูลเองได้ด้วยการเขียน `: ชนิด` หลังชื่อตัวแปร
    let x: i32 = 5; // i32 = จำนวนเต็มแบบมีเครื่องหมาย ขนาด 32 บิต
    let z: bool = true; // bool = ค่าความจริง มีแค่ true หรือ false
    let c: char = 'A'; // char = ตัวอักษร 1 ตัว (ใช้ ' ' ไม่ใช่ " ")
    println!("x: {}, z: {}, c: {}", x, z, c);

    // ส่งตัวแปรเข้าไปแบบยืม (&) ให้ฟังก์ชัน type_of เพื่อพิมพ์ชื่อชนิดข้อมูลออกมา
    println!(
        "Type of x: {}, Type of z: {}, Type of c: {}",
        type_of(&x),
        type_of(&z),
        type_of(&c)
    );
}
